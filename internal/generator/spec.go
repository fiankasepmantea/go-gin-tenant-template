// Package generator creates the files of a new module (`tenantctl make:module`) and of a new migration
// (`tenantctl make:migration`). The output follows the conventions of docs/http-api.md and docs/rbac.md, so
// a generated module is tenant-isolated (row level security), paginated, filterable and protected by RBAC
// from the first run.
package generator

import (
	"errors"
	"fmt"
	"go/token"
	"regexp"
	"slices"
	"strings"
)

var (
	nameRe  = regexp.MustCompile(`^[a-z][a-z0-9]{1,30}$`)
	identRe = regexp.MustCompile(`^[a-z][a-z0-9_]{0,40}$`)
	tableRe = regexp.MustCompile(`^[a-z][a-z0-9_]{1,50}$`)
)

// Field types accepted in --field name:type.
const (
	TString = "string" // text, up to 255 characters
	TText   = "text"   // text, up to 5000 characters
	TInt    = "int"
	TBigint = "bigint"
	TFloat  = "float"
	TBool   = "bool"
	TTime   = "time" // timestamptz
	TUUID   = "uuid"
)

var fieldTypes = []string{TString, TText, TInt, TBigint, TFloat, TBool, TTime, TUUID}

// maxIdentifier is the longest identifier PostgreSQL keeps (longer names are silently cut, which can collide).
const maxIdentifier = 63

// modelNames are the names of the generated model's own fields and methods; a column cannot use them.
var modelNames = []string{"ID", "Unique", "TenantID", "CreatedAt", "UpdatedAt", "DeletedAt", "TableName", "PrimaryKey", "GetID", "SetID", "SetTenantID"}

// maxFields keeps a generated module readable; a table with more columns is written by hand.
const maxFields = 30

// reservedPackages cannot be module names: they are packages of the template, or they would shadow an
// identifier in internal/app.
var reservedPackages = []string{
	"app", "core", "auth", "session", "user", "tenant", "group", "rbac", "endpoint", "appversion",
	"platform", "rest", "config", "cli", "version", "middleware", "crud", "response", "request", "gin", "gorm",
	"test", "main", "module", "modules", "context", "errors", "http", "time", "strings", "slog", "fmt",
}

// reservedTables are tables of the template.
var reservedTables = []string{
	"tenants", "users", "groups", "endpoints", "group_endpoints", "user_tokens", "app_versions",
	"password_resets", "schema_migrations",
}

// reservedColumns are generated by the template for every table.
var reservedColumns = []string{"id", "tenant_id", "created_at", "updated_at", "deleted_at"}

// sqlWords cannot be column names: the generated SQL does not quote identifiers.
var sqlWords = []string{
	"all", "alter", "and", "as", "asc", "by", "case", "check", "column", "constraint", "create", "default",
	"delete", "desc", "distinct", "drop", "else", "end", "false", "from", "grant", "group", "having", "in",
	"index", "insert", "into", "is", "join", "key", "like", "limit", "not", "null", "offset", "on", "or",
	"order", "primary", "references", "select", "set", "table", "then", "true", "union", "unique", "update", "user",
	"using", "values", "when", "where", "window", "with",
}

// Field is one column of the new table.
type Field struct {
	Name     string // snake_case column name
	Type     string // one of the T* constants
	Required bool   // "name:type!": NOT NULL without default, required in the create request
}

// ParseField reads "name:type" or "name:type!".
func ParseField(s string) (Field, error) {
	name, typ, ok := strings.Cut(strings.TrimSpace(s), ":")
	if !ok {
		return Field{}, fmt.Errorf("field %q: write it as name:type (types: %s)", s, strings.Join(fieldTypes, ", "))
	}
	required := strings.HasSuffix(typ, "!")
	typ = strings.TrimSuffix(typ, "!")
	if !identRe.MatchString(name) || strings.HasSuffix(name, "_") || strings.Contains(name, "__") {
		return Field{}, fmt.Errorf("field %q: the name must be lowercase letters, digits and single underscores, starting with a letter", name)
	}
	if !slices.Contains(fieldTypes, typ) {
		return Field{}, fmt.Errorf("field %q: unknown type %q (types: %s)", name, typ, strings.Join(fieldTypes, ", "))
	}
	return Field{Name: name, Type: typ, Required: required}, nil
}

// ModuleSpec is what the user asked for, validated.
type ModuleSpec struct {
	Name   string // package name, singular, e.g. "product"
	Table  string // e.g. "products"
	Fields []Field
	Unique []string // field names that get a unique index per tenant
}

// NewModuleSpec validates the input of make:module. table may be empty (derived from name).
func NewModuleSpec(name, table string, fields, unique []string) (*ModuleSpec, error) {
	name = strings.TrimSpace(name)
	switch {
	case !nameRe.MatchString(name):
		return nil, fmt.Errorf("module name %q: use 2-31 lowercase letters and digits, starting with a letter, singular (for example: product)", name)
	case token.IsKeyword(name), slices.Contains(reservedPackages, name), isPredeclared(name):
		return nil, fmt.Errorf("module name %q is reserved: choose another one", name)
	}
	if table == "" {
		table = Pluralize(name)
	}
	if !tableRe.MatchString(table) || strings.HasSuffix(table, "_") || strings.Contains(table, "__") {
		return nil, fmt.Errorf("table name %q: use lowercase letters, digits and single underscores", table)
	}
	if slices.Contains(reservedTables, table) || slices.Contains(sqlWords, table) {
		return nil, fmt.Errorf("table name %q is reserved: choose another one with --table", table)
	}

	s := &ModuleSpec{Name: name, Table: table}
	if len(fields) == 0 {
		return nil, errors.New("give at least one field, for example --field name:string! --field price:int")
	}
	if len(fields) > maxFields {
		return nil, fmt.Errorf("at most %d fields: write a table with more columns by hand", maxFields)
	}
	seen := map[string]bool{}
	goNames := map[string]string{}
	for _, raw := range fields {
		f, err := ParseField(raw)
		if err != nil {
			return nil, err
		}
		switch {
		case slices.Contains(reservedColumns, f.Name), f.Name == name+"_id", f.Name == name+"_unique":
			return nil, fmt.Errorf("field %q is created by the template for every table", f.Name)
		case slices.Contains(sqlWords, f.Name):
			return nil, fmt.Errorf("field %q is an SQL keyword: choose another name", f.Name)
		case seen[f.Name]:
			return nil, fmt.Errorf("field %q is given twice", f.Name)
		}
		if slices.Contains(modelNames, Pascal(f.Name)) {
			return nil, fmt.Errorf("field %q: its Go name %s is already used by the model", f.Name, Pascal(f.Name))
		}
		if other, dup := goNames[Pascal(f.Name)]; dup {
			return nil, fmt.Errorf("fields %q and %q have the same Go name %s", other, f.Name, Pascal(f.Name))
		}
		goNames[Pascal(f.Name)] = f.Name
		seen[f.Name] = true
		s.Fields = append(s.Fields, f)
	}
	for _, u := range unique {
		f, ok := s.field(u)
		switch {
		case !ok:
			return nil, fmt.Errorf("--unique %q: there is no such field", u)
		case f.Type == TText || f.Type == TFloat || f.Type == TBool:
			return nil, fmt.Errorf("--unique %q: a %s field cannot be unique", u, f.Type)
		case !f.Required:
			return nil, fmt.Errorf("--unique %q: make the field required (%s:%s!)", u, f.Name, f.Type)
		case slices.Contains(s.Unique, u):
			return nil, fmt.Errorf("--unique %q is given twice", u)
		}
		s.Unique = append(s.Unique, u)
	}
	for _, id := range s.identifiers() {
		if len(id) > maxIdentifier {
			return nil, fmt.Errorf("the generated name %q is longer than the %d characters PostgreSQL allows: use shorter names", id, maxIdentifier)
		}
	}
	return s, nil
}

func (s *ModuleSpec) field(name string) (Field, bool) {
	for _, f := range s.Fields {
		if f.Name == name {
			return f, true
		}
	}
	return Field{}, false
}

// Pluralize makes the default table name from the module name. It handles the regular English rules only;
// use --table for anything else.
func Pluralize(s string) string {
	switch {
	case strings.HasSuffix(s, "s"), strings.HasSuffix(s, "x"), strings.HasSuffix(s, "z"),
		strings.HasSuffix(s, "ch"), strings.HasSuffix(s, "sh"):
		return s + "es"
	case len(s) > 1 && strings.HasSuffix(s, "y") && !strings.ContainsRune("aeiou", rune(s[len(s)-2])):
		return s[:len(s)-1] + "ies"
	default:
		return s + "s"
	}
}

var predeclared = []string{
	"any", "append", "bool", "byte", "cap", "clear", "close", "comparable", "complex", "complex128", "complex64",
	"copy", "delete", "error", "false", "float32", "float64", "imag", "int", "int16", "int32", "int64", "int8",
	"iota", "len", "make", "max", "min", "new", "nil", "panic", "print", "println", "real", "recover", "rune",
	"string", "true", "uint", "uint16", "uint32", "uint64", "uint8", "uintptr",
}

func isPredeclared(s string) bool { return slices.Contains(predeclared, s) }

// initialisms are written in capitals in Go names.
var initialisms = map[string]string{"id": "ID", "url": "URL", "uri": "URI", "api": "API", "ip": "IP", "uuid": "UUID", "http": "HTTP", "sku": "SKU"}

// Pascal turns snake_case into a Go name: "unit_price" -> "UnitPrice", "image_url" -> "ImageURL".
func Pascal(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part == "" {
			continue
		}
		if up, ok := initialisms[part]; ok {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

// identifiers lists the constraint, index and trigger names the migration creates.
func (s *ModuleSpec) identifiers() []string {
	ids := []string{
		s.Table + "_tenant_" + s.Name + "_uq", s.Table + "_tenant_idx", s.Table + "_updated_at",
	}
	for _, u := range s.Unique {
		ids = append(ids, s.Table+"_tenant_"+u+"_uq")
	}
	return ids
}

// IDColumn is the primary key column, e.g. product_id.
func (s *ModuleSpec) IDColumn() string { return s.Name + "_id" }

// UniqueColumn is the identity column, e.g. product_unique.
func (s *ModuleSpec) UniqueColumn() string { return s.Name + "_unique" }

// Type is the Go type name of the model, e.g. Product.
func (s *ModuleSpec) Type() string { return Pascal(s.Name) }
